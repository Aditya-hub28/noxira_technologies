const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = p => fs.readFileSync(path.join(__dirname, '..', 'src', p), 'utf8');
const css = read('heroes.css');
const button = css.match(/\.gb\s*\{([\s\S]*?)\}/)[1];
for (const rule of ['display: inline-flex', 'align-items: center', 'justify-content: center', 'max-width: 100%', 'min-width: 0']) assert.ok(button.includes(rule), rule);
assert.ok(button.indexOf('display: inline-flex') > button.indexOf('all: unset'));
assert.match(css, /\.gb > svg\s*\{\s*flex-shrink: 0/);
console.log('PASS: shared glass buttons own flex layout after reset and keep icons from shrinking');
const home = read('pages/HomePage.jsx');
assert.equal((home.match(/<CertificateShowcase\s*\/>/g) || []).length, 1);
assert.match(home, /<CertificateShowcase\s*\/>\s*\{\/\*[\s\S]*?\*\/\}\s*<ReviewMarquee\s*\/>/);
assert.ok(home.indexOf('id="contact"') < home.indexOf('<CertificateShowcase />'));
assert.ok(!home.includes('id="verification-teaser"'));
console.log('PASS: one certificate section follows Contact and directly precedes existing feedback');
const component = read('components/CertificateShowcase.jsx');
for (const route of ['/apply', '/verify', '/offer-letter']) assert.ok(component.includes(`to="${route}"`));
for (const label of ['NOT ISSUED', 'SAMPLE PREVIEW ONLY', 'No credential ID assigned', 'Your name here']) assert.ok(component.includes(label));
assert.ok(component.includes('src="/noxira-wordmark.png"'));
assert.ok(!component.includes('download='));
assert.ok(!/recognized|accredited|trusted by thousands|Verified &amp; Valid/i.test(component));
console.log('PASS: demo is explicit, original logo used, and actions target supported routes');

assert.ok(!home.includes('Start your practical engineering journey with NOXIRA.'));
assert.ok(!home.includes('>Apply.</h2>'));
assert.match(home, /<ReviewMarquee\s*\/>[\s\S]*?<div className="home-copyright">/);
assert.ok(home.includes('NOXIRA TECHNOLOGIES'));
console.log('PASS: closing Apply section removed while feedback and copyright footer remain');
