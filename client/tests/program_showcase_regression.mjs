import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { MemoryRouter } from 'react-router-dom';
const require=createRequire(import.meta.url);
const client=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const catalogue=require('../../server/src/config/programsCatalogue.js').CATALOGUE_PROGRAMS;
const configured=await import(pathToFileURL(path.join(client,'src/config/programmeCatalogue.js')));
assert.deepEqual(configured.CONFIGURED_PROGRAMMES,catalogue);
assert.equal(catalogue.length,31);
assert.ok(!catalogue.some(p=>p.category==='Emerging Tech'));
console.log('PASS: all31 configured identities exactly match owner catalogue; no Emerging Tech');
const out=path.join(client,'node_modules/.cache/program-showcase-tests');
execFileSync(process.execPath,[path.join(client,'node_modules/vite/bin/vite.js'),'build','--ssr','src/components/ProgramShowcase.jsx','--outDir',out],{cwd:client,stdio:'pipe'});
const {default:Showcase}=await import(pathToFileURL(path.join(out,'ProgramShowcase.js')));
const render=props=>renderToStaticMarkup(React.createElement(MemoryRouter,null,React.createElement(Showcase,{programs:[],loading:false,...props})));
const home=render({programs:catalogue,configured:true});
assert.equal((home.match(/class="program-card"/g)||[]).length,6);
assert.equal((home.match(/href="\/apply"/g)||[]).length,13);
assert.ok(!home.includes('href="/programs"'));
assert.match(home,/31 configured programmes/);
assert.ok(!home.includes('Layout sample'));
console.log('PASS: six home cards and View All share full catalogue destination, with honest status');
assert.match(render({}),/No programmes published yet/);
assert.match(render({loading:true}),/aria-busy="true"/);
const live=render({programs:[{code:'OWNER',title:'Owner Programme',description:'Owner content',category:'Engineering',feeInr:99}]});
assert.match(live,/Owner content/);assert.ok(!live.includes('99'));assert.ok(!live.includes('configured programmes'));
console.log('PASS: loading, successful empty, live owner content and fee hiding preserved');
const source=fs.readFileSync(path.join(client,'src/pages/HomePage.jsx'),'utf8');
assert.equal((source.match(/<ProgramShowcase /g)||[]).length,1);
assert.match(source,/<ProgramShowcase[^>]*\/>\s*<CertificateShowcase\s*\/>/);
console.log('PASS: single programme showcase directly precedes certificate');
const {PROGRAMME_IMAGES}=await import(pathToFileURL(path.join(client,'src/config/programmeImages.js')));
const imageSources=JSON.parse(fs.readFileSync(path.join(client,'public/programme-images/sources.json'),'utf8'));
assert.deepEqual(Object.keys(PROGRAMME_IMAGES).sort(),catalogue.map(p=>p.code).sort());
assert.equal(new Set(imageSources.map(p=>p.photo)).size,31);
assert.ok(imageSources.every(p=>!p.paid && p.originalWidth>=3840 && p.originalHeight>=2160 && p.kind==='Real Pexels photograph' && p.license==='https://www.pexels.com/license/'));
for(const image of Object.values(PROGRAMME_IMAGES)) {
 assert.ok(image.alt.length>0);
 for(const src of [image.src,image.small]) assert.ok(fs.statSync(path.join(client,'public',src)).size>1000);
}
console.log('PASS:31distinct real Pexels photographs, native4K source dimensions, license provenance, local responsive assets and alt text');
